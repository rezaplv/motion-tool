import type { BackgroundSetting, MotionLayer, UploadedAsset } from "../types";

/**
 * Kode Canvas untuk Visual Layer (mode CANVAS).
 * Format: function draw(ctx, time, width, height, assets). Gambar diambil dari assets[assetId].
 */
export function generateCanvasBuilderCode(
  layers: MotionLayer[],
  background: BackgroundSetting,
  _assets: UploadedAsset[],
  duration: number
): string {
  return `// Generated by Visual Layer Builder (Canvas)
const layers = ${JSON.stringify(layers, null, 2)};
const bgSetting = ${JSON.stringify(background, null, 2)};
const DURATION = ${Math.max(1, duration)};

function easeOutCubic(t) { return 1 - Math.pow(1 - t, 3); }
function easeInCubic(t) { return t * t * t; }
function easeInOutCubic(t) { return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2; }
function easeOutBack(t) { const c1 = 1.70158, c3 = c1 + 1; return 1 + c3 * Math.pow(t - 1, 3) + c1 * Math.pow(t - 1, 2); }
function easeInBack(t) { const c1 = 1.70158, c3 = c1 + 1; return c3 * t * t * t - c1 * t * t; }
function easeOutElastic(x) { const c4 = (2 * Math.PI) / 3; return x === 0 ? 0 : x === 1 ? 1 : Math.pow(2, -10 * x) * Math.sin((x * 10 - 0.75) * c4) + 1; }
function easeOutBounce(x) {
  const n1 = 7.5625, d1 = 2.75;
  if (x < 1 / d1) return n1 * x * x;
  if (x < 2 / d1) return n1 * (x -= 1.5 / d1) * x + 0.75;
  if (x < 2.5 / d1) return n1 * (x -= 2.25 / d1) * x + 0.9375;
  return n1 * (x -= 2.625 / d1) * x + 0.984375;
}
const EASINGS = { linear: (t) => t, easeOutCubic, easeInCubic, easeInOutCubic, easeOutBack, easeInBack, easeOutElastic, easeOutBounce };

function layerT(layer, p) {
  const start = layer.entryDelay, end = Math.min(1, layer.entryDelay + layer.entryDuration);
  if (end <= start) return 1;
  const t = Math.min(1, Math.max(0, (p - start) / (end - start)));
  return (EASINGS[layer.easing] || EASINGS.linear)(t);
}

function drawBackground(ctx, width, height) {
  if (bgSetting.type === "solid") {
    ctx.fillStyle = bgSetting.color;
  } else {
    const d = bgSetting.direction || "vertical";
    let g;
    if (d === "radial") g = ctx.createRadialGradient(width / 2, height / 2, 0, width / 2, height / 2, Math.max(width, height) * 0.75);
    else if (d === "horizontal") g = ctx.createLinearGradient(0, 0, width, 0);
    else if (d === "diagonal") g = ctx.createLinearGradient(0, 0, width, height);
    else g = ctx.createLinearGradient(0, 0, 0, height);
    g.addColorStop(0, bgSetting.color);
    g.addColorStop(1, bgSetting.colorTo || bgSetting.color);
    ctx.fillStyle = g;
  }
  ctx.fillRect(0, 0, width, height);
}

function roundRect(ctx, x, y, w, h, r) {
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}

function draw(ctx, time, width, height, assets) {
  const p = Math.min(1, time / DURATION);
  drawBackground(ctx, width, height);

  for (const layer of layers) {
    const t = layerT(layer, p);
    const x = (layer.x / 100) * width, y = (layer.y / 100) * height;
    const w = (layer.width / 100) * width, h = (layer.height / 100) * height;
    const cx = x + w / 2, cy = y + h / 2;
    const scale = 0.85 + 0.15 * t;

    ctx.save();
    ctx.globalAlpha = Math.max(0, Math.min(1, layer.opacity * t));
    ctx.translate(cx, cy);
    ctx.rotate((layer.rotation * Math.PI) / 180);
    ctx.scale(scale, scale);
    ctx.translate(-cx, -cy);
    ctx.fillStyle = layer.color;

    if (layer.type === "text") {
      ctx.font = (layer.fontWeight || 700) + " " + ((layer.fontSize || 8) / 100) * height + "px Inter, Arial, sans-serif";
      ctx.textAlign = "center";
      ctx.textBaseline = "middle";
      ctx.fillText(layer.text || "", cx, cy);
    } else if (layer.type === "shape") {
      if (layer.shapeKind === "circle") {
        ctx.beginPath();
        ctx.arc(cx, cy, Math.min(w, h) / 2, 0, Math.PI * 2);
        ctx.fill();
      } else if (layer.shapeKind === "ellipse") {
        ctx.beginPath();
        ctx.ellipse(cx, cy, w / 2, h / 2, 0, 0, Math.PI * 2);
        ctx.fill();
      } else {
        roundRect(ctx, x, y, w, h, Math.min(w, h) * 0.08);
        ctx.fill();
      }
    } else if (layer.type === "image") {
      const img = assets && assets[layer.assetId];
      if (img && img.naturalWidth) {
        // Fit (contain) di dalam kotak layer.
        const s = Math.min(w / img.naturalWidth, h / img.naturalHeight);
        const dw = img.naturalWidth * s, dh = img.naturalHeight * s;
        ctx.drawImage(img, cx - dw / 2, cy - dh / 2, dw, dh);
      }
    }
    ctx.restore();
  }
}
`;
}
