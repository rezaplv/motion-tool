import type { BackgroundSetting, MotionLayer, UploadedAsset } from "../types";

/**
 * Menghasilkan kode JavaScript fungsi draw() dari layer-layer dan background
 * yang disusun lewat Asset Motion Builder (mode GUI, tanpa AI).
 * Asset gambar yang dipakai layer di-embed sebagai data URL agar kode tetap mandiri.
 */
export function generateBuilderCode(
  layers: MotionLayer[],
  background: BackgroundSetting,
  assets: UploadedAsset[] = []
): string {
  const layersJson = JSON.stringify(layers, null, 2);
  const bgJson = JSON.stringify(background, null, 2);
  const usedIds = new Set(layers.filter((l) => l.type === "image" && l.assetId).map((l) => l.assetId));
  const assetMap: Record<string, string> = {};
  for (const a of assets) {
    if (usedIds.has(a.id)) assetMap[a.id] = a.dataUrl;
  }

  return `// Generated by Asset Motion Builder
const layers = ${layersJson};
const bgSetting = ${bgJson};
const assetMap = ${JSON.stringify(assetMap)};

function easeOutCubic(t) { return 1 - Math.pow(1 - t, 3); }
function easeInCubic(t) { return t * t * t; }
function easeInOutCubic(t) { return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2; }
function easeOutBack(t) {
  const c1 = 1.70158, c3 = c1 + 1;
  return 1 + c3 * Math.pow(t - 1, 3) + c1 * Math.pow(t - 1, 2);
}
function easeInBack(t) {
  const c1 = 1.70158, c3 = c1 + 1;
  return c3 * t * t * t - c1 * t * t;
}
function easeOutElastic(x) {
  const c4 = (2 * Math.PI) / 3;
  return x === 0 ? 0 : x === 1 ? 1 : Math.pow(2, -10 * x) * Math.sin((x * 10 - 0.75) * c4) + 1;
}
function easeOutBounce(x) {
  const n1 = 7.5625, d1 = 2.75;
  if (x < 1 / d1) return n1 * x * x;
  if (x < 2 / d1) return n1 * (x -= 1.5 / d1) * x + 0.75;
  if (x < 2.5 / d1) return n1 * (x -= 2.25 / d1) * x + 0.9375;
  return n1 * (x -= 2.625 / d1) * x + 0.984375;
}
const EASINGS = { linear: (t) => t, easeOutCubic, easeInCubic, easeInOutCubic, easeOutBack, easeInBack, easeOutElastic, easeOutBounce };

function layerProgress(layer, progress) {
  const start = layer.entryDelay;
  const end = Math.min(1, layer.entryDelay + layer.entryDuration);
  if (end <= start) return 1;
  const t = (progress - start) / (end - start);
  const clamped = Math.min(1, Math.max(0, t));
  const ease = EASINGS[layer.easing] || EASINGS.linear;
  return ease(clamped);
}

function renderBackground(width, height) {
  if (bgSetting.type === "solid") {
    return \`<rect width="\${width}" height="\${height}" fill="\${bgSetting.color}" />\`;
  }
  const dir = bgSetting.direction || "vertical";
  if (dir === "radial") {
    return \`
      <radialGradient id="bgGrad" cx="50%" cy="50%" r="75%">
        <stop offset="0%" stop-color="\${bgSetting.color}" />
        <stop offset="100%" stop-color="\${bgSetting.colorTo || bgSetting.color}" />
      </radialGradient>
      <rect width="\${width}" height="\${height}" fill="url(#bgGrad)" />\`;
  }
  const coords =
    dir === "horizontal"
      ? 'x1="0%" y1="0%" x2="100%" y2="0%"'
      : dir === "diagonal"
      ? 'x1="0%" y1="0%" x2="100%" y2="100%"'
      : 'x1="0%" y1="0%" x2="0%" y2="100%"';
  return \`
    <linearGradient id="bgGrad" \${coords}>
      <stop offset="0%" stop-color="\${bgSetting.color}" />
      <stop offset="100%" stop-color="\${bgSetting.colorTo || bgSetting.color}" />
    </linearGradient>
    <rect width="\${width}" height="\${height}" fill="url(#bgGrad)" />\`;
}

function escapeXml(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

// Semua posisi/ukuran layer dalam PERSEN kanvas (0-100) agar hasil sama di 720p sampai 4K.
function renderLayer(layer, width, height, t) {
  const x = (layer.x / 100) * width;
  const y = (layer.y / 100) * height;
  const w = (layer.width / 100) * width;
  const h = (layer.height / 100) * height;
  const opacity = layer.opacity * t;
  const scale = 0.85 + 0.15 * t;
  const cx = x + w / 2;
  const cy = y + h / 2;
  const transform = \`translate(\${cx} \${cy}) scale(\${scale}) rotate(\${layer.rotation}) translate(\${-cx} \${-cy})\`;

  if (layer.type === "text") {
    const fontSize = ((layer.fontSize || 8) / 100) * height;
    return \`<text x="\${cx}" y="\${cy}" fill="\${layer.color}" font-family="Inter, Arial, sans-serif" font-size="\${fontSize}" font-weight="\${layer.fontWeight || 700}" text-anchor="middle" dominant-baseline="middle" opacity="\${opacity}" transform="\${transform}">\${escapeXml(layer.text || "")}</text>\`;
  }

  if (layer.type === "shape") {
    if (layer.shapeKind === "circle") {
      const r = Math.min(w, h) / 2;
      return \`<circle cx="\${cx}" cy="\${cy}" r="\${r}" fill="\${layer.color}" opacity="\${opacity}" transform="\${transform}" />\`;
    }
    if (layer.shapeKind === "ellipse") {
      return \`<ellipse cx="\${cx}" cy="\${cy}" rx="\${w / 2}" ry="\${h / 2}" fill="\${layer.color}" opacity="\${opacity}" transform="\${transform}" />\`;
    }
    return \`<rect x="\${x}" y="\${y}" width="\${w}" height="\${h}" rx="\${Math.min(w, h) * 0.08}" fill="\${layer.color}" opacity="\${opacity}" transform="\${transform}" />\`;
  }

  if (layer.type === "image") {
    const href = assetMap[layer.assetId];
    if (!href) return "";
    return \`<image href="\${href}" x="\${x}" y="\${y}" width="\${w}" height="\${h}" preserveAspectRatio="xMidYMid meet" opacity="\${opacity}" transform="\${transform}" />\`;
  }

  return "";
}

function draw(svg, width, height, frame, progress) {
  const bg = renderBackground(width, height);
  const layerSvg = layers
    .map((layer) => renderLayer(layer, width, height, layerProgress(layer, progress)))
    .join("\\n");

  svg.innerHTML = \`<defs></defs>\${bg}\${layerSvg}\`;
}
`;
}
